"""Regenerate the report's results tables from saved experiment outputs (no recomputation).

Table 1: local paired LOBO results (results/paired*.csv). Table 2: live arms from formative feedback
(submissions/feedback/*.json, *.txt) with pooling-aware two-way fixed effects. Writes report/tables.md.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "tools"))
from feedback import BUDGETS, fixed_effects, ledger_arms, load  # noqa: E402

LOCAL = [  # (csv, model column, label)
    ("results/paired.csv", "const_0.5", "Constant 0.5"),
    ("results/paired.csv", "empirical_mean", "Organizer empirical mean"),
    ("results/paired.csv", "smoothed_k2", "Smoothed mean (kappa=2)"),
    ("results/paired.csv", "v1_tuned", "v1 hierarchical (tuned)"),
    ("results/paired_subjects.csv", "v1_subjects", "+ subject prior (names + attributes)"),
    ("results/paired_damped.csv", "n15D", "+ damped Newton, m0=-1.5"),
    ("results/paired_damped.csv", "n20D", "+ damped Newton, m0=-2.0"),
    ("results/paired_mix.csv", "mix25_m10", "+ zero-inflated mixture (pi=0.25), m0=-1.0"),
]


def local_table() -> str:
    rows = []
    for csv, model, label in LOCAL:
        df = pd.read_csv(REPO / csv)
        d = df[df.model == model]
        macro = d.groupby(["bench", "k"])["alc"].mean().groupby(level=0).mean().mean()
        per_b = d[[f"b{b}" for b in BUDGETS]].mean()
        rows.append(f"| {label} | {macro:.4f} | " + " | ".join(f"{per_b[f'b{b}']:.3f}" for b in BUDGETS) + " |")
    head = "| Model | Brier ALC (bench-equal) | " + " | ".join(f"B{b}" for b in BUDGETS) + " |"
    sep = "|" + "---|" * (2 + len(BUDGETS))
    note = ("\nNote: rows from different CSVs use different draw sets (20-30 draws per held-out benchmark and "
            "composition); compare within a CSV for paired differences.")
    return "\n".join([head, sep, *rows]) + note


def live_table(ref: str = "v3b_noM_n_m20") -> str:
    df = load()
    arm_of = dict(sorted(ledger_arms().items(), key=lambda kv: kv[1] != ref))
    fe = {sec: fixed_effects(df, arm_of, sec).set_index("arm") for sec in ("alc", "b0", "b1", "b3")}
    a = df[df.section == "alc"].copy()
    a["arm"] = a["submission"].map(arm_of)
    raw = a.groupby("arm").agg(runs=("submission", "nunique"), pairs=("score", "size"), raw=("score", "mean"))
    col = f"effect_vs_{ref}"
    lines = [f"| Arm | runs | pairs | raw mean ALC | FE ALC vs {ref} | shared | FE B0 | FE B1 | FE B3 |",
             "|---|---|---|---|---|---|---|---|---|"]
    for arm in fe["alc"].index:
        if arm not in raw.index:
            continue
        r = raw.loc[arm]
        e = {sec: fe[sec].loc[arm, col] for sec in fe}
        lines.append(f"| {arm} | {int(r.runs)} | {int(r.pairs)} | {r.raw:.4f} | {e['alc']:+.4f} | "
                     f"{int(fe['alc'].loc[arm, 'pairs_shared'])} | {e['b0']:+.4f} | {e['b1']:+.4f} | {e['b3']:+.4f} |")
    return "\n".join(lines)


def main() -> None:
    out = ["# Results tables (generated by report/make_tables.py)", "", "## Table 1. Local paired LOBO replay", "",
           local_table(), "", "## Table 2. Live formative feedback, pooling-aware fixed effects", "", live_table()]
    (REPO / "report" / "tables.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
