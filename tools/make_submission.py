"""Assemble submission_src/<name>/ for the hierarchical model: one self-contained model.py + params + subject prior.

model.py vendors paiec/subjects.py and paiec/hier.py (docstrings stripped) so the zip needs no package imports.
The subject prior is fitted on all public training-pool benchmarks (measurement-db revision bc8204d8).

Plug-ins: --plugin paiec.ext.<module>:<Class> (or a "class" key inside --params) also vendors that module after hier.py
and ships <Class>(prior, params) instead of HierModel. The module docstring, the `from __future__` line and every paiec
import are removed (the vendored code above already defines those names; `import X as Y` becomes `Y = X`), and a
plug-in that imports another paiec.ext module gets that module vendored first. A plug-in's own top-level definition
that would overwrite a vendored global (e.g. its own `_sigmoid`) is renamed name__<module> at every use. The build
fails if an imported name is not defined above or if any paiec import is left. params.json keeps "class"
for provenance (tools/verify_shipped.py builds the research model from it); the shipped code drops that key before
constructing the model. Without a plug-in the output is byte-identical to the previous version of this tool.

--outdir DIR writes the three files to DIR instead of submission_src/<name> (the name still goes into the model.py
header), e.g. to check that a rebuild reproduces an existing submission byte for byte without touching it.
"""
