VENDORED_CORE = ("paiec.subjects", "paiec.hier")  # already in model.py, in this order


def _code(path: Path) -> str:
    body = path.read_text().split('"""', 2)[2]  # drop module docstring
    return body.replace("from __future__ import annotations\n", "")


# ------------------------------------------------------------------------------------------------- plug-in vendoring
def _absolute(module: str, node: ast.ImportFrom) -> str:
    """Absolute module name of an ImportFrom inside `module` (handles `from .x import y`)."""
    if not node.level:
        return node.module or ""
    base = module.split(".")[: -node.level]
    return ".".join(base + ([node.module] if node.module else []))


def _paiec_target(module: str, node) -> str | None:
    """The paiec module an import statement pulls from, or None for any other import."""
    if isinstance(node, ast.ImportFrom):
        target = _absolute(module, node)
        return target if target.split(".")[0] == "paiec" else None
    if isinstance(node, ast.Import):
        hits = [a.name for a in node.names if a.name.split(".")[0] == "paiec"]
        if hits:
            raise SystemExit(f"{module}: `import {hits[0]}` cannot be vendored; use `from {hits[0]} import Name`")
    return None


def _bindings(tree: ast.Module) -> tuple[dict, set]:
    """Top-level names: {imported name: (module, attr)} and the set of names bound by def/class/assignment."""
    imports, defs = {}, set()

    def visit(nodes):
        for node in nodes:
            if isinstance(node, ast.Import):
                for a in node.names:
                    imports[a.asname or a.name.split(".")[0]] = (a.name if a.asname else a.name.split(".")[0], None)
            elif isinstance(node, ast.ImportFrom):
                for a in node.names:
                    imports[a.asname or a.name] = ("." * node.level + (node.module or ""), a.name)
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                defs.add(node.name)
            elif isinstance(node, (ast.Assign, ast.AnnAssign, ast.AugAssign)):
                for t in (node.targets if isinstance(node, ast.Assign) else [node.target]):
                    defs.update(n.id for n in ast.walk(t) if isinstance(n, ast.Name))
            elif isinstance(node, (ast.Try, ast.If, ast.With, ast.For, ast.While)):
                visit(node.body)
                visit(getattr(node, "orelse", []))
                for h in getattr(node, "handlers", []):
                    visit(h.body)
                visit(getattr(node, "finalbody", []))

    visit(tree.body)
    return imports, defs


def _rename(module: str, code: str, names: set, suffix: str) -> str:
    """Rename the plug-in's own top-level `names` (which would overwrite vendored globals in the shared model.py
    namespace) to name+suffix at every non-attribute use. Refuses the cases a token-level rename cannot do safely."""
    tree = ast.parse(code)
    for node in ast.walk(tree):
        risky = None
        if isinstance(node, ast.keyword) and node.arg in names:
            risky = f"keyword argument {node.arg}="
        elif isinstance(node, (ast.Global, ast.Nonlocal)) and set(node.names) & names:
            risky = "global/nonlocal statement"
        elif isinstance(node, ast.ClassDef):
            for stmt in node.body:
                bound = {stmt.name} if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) else {
                    n.id for t in getattr(stmt, "targets", [getattr(stmt, "target", None)]) if t is not None
                    for n in ast.walk(t) if isinstance(n, ast.Name)}
                if bound & names:
                    risky = f"class attribute {sorted(bound & names)[0]} in {node.name}"
        if risky:
            raise SystemExit(f"{module}: cannot rename {sorted(names)} automatically ({risky}); rename it in the "
                             f"plug-in source")
    lines = code.splitlines(keepends=True)
    hits, prev = [], None
    for tok in tokenize.generate_tokens(io.StringIO(code).readline):
        if tok.type == tokenize.NAME and tok.string in names and not (prev and prev.string == "."):
            hits.append((tok.start[0], tok.start[1], tok.end[1]))
        if tok.type not in (tokenize.NL, tokenize.NEWLINE, tokenize.COMMENT, tokenize.INDENT, tokenize.DEDENT):
            prev = tok
    for row, c0, c1 in sorted(hits, reverse=True):
        lines[row - 1] = lines[row - 1][:c1] + suffix + lines[row - 1][c1:]
    out = "".join(lines)
    left = sorted({n.id for n in ast.walk(ast.parse(out)) if isinstance(n, ast.Name) and n.id in names})
    if left:  # e.g. a use inside an f-string, which the tokenizer does not split on Python < 3.12
        raise SystemExit(f"{module}: could not rename every use of {left}; rename it in the plug-in source")
    print(f"note: {module}: renamed {sorted(names)} -> *{suffix} (already defined by the vendored code)",
          file=sys.stderr)
    return out


def _module_path(module: str) -> Path:
    return REPO / Path(*module.split(".")).with_suffix(".py")


def _plugin_order(module: str, seen: list[str], stack: tuple = ()) -> list[str]:
    """paiec.ext modules to vendor, dependencies first."""
    if module in seen:
        return seen
    if module in stack:
        raise SystemExit(f"circular plug-in imports: {' -> '.join(stack + (module,))}")
    path = _module_path(module)
    if not module.startswith("paiec.ext.") or not path.is_file():
        raise SystemExit(f"plug-in module {module} not found under paiec/ext/")
    for node in ast.walk(ast.parse(path.read_text())):
        target = _paiec_target(module, node) if isinstance(node, (ast.Import, ast.ImportFrom)) else None
        if target and target not in VENDORED_CORE:
            if not target.startswith("paiec.ext."):
                raise SystemExit(f"{module} imports {target}, which is not vendored into model.py "
                                 f"(only {', '.join(VENDORED_CORE)} and paiec.ext modules are)")
            _plugin_order(target, seen, stack + (module,))
    seen.append(module)
    return seen


def _strip_plugin(module: str, available: dict, available_defs: set) -> tuple[str, dict, set]:
    """Source of one plug-in module ready to append to model.py, plus its new top-level bindings."""
    src = _module_path(module).read_text()
    tree = ast.parse(src)
    lines = src.splitlines(keepends=True)
    cut = []  # (first line, last line, replacement text), 1-based inclusive

    def is_paiec(node) -> bool:
        return isinstance(node, (ast.Import, ast.ImportFrom)) and _paiec_target(module, node) is not None

    def aliases(nodes) -> str:
        out = []
        for node in nodes:
            target = _paiec_target(module, node)
            for a in node.names:
                if a.name == "*":
                    raise SystemExit(f"{module}: `from {target} import *` cannot be vendored")
                if a.name not in available and a.name not in available_defs:
                    raise SystemExit(f"{module} imports {a.name} from {target}, but no vendored code defines it")
                if a.asname and a.asname != a.name:
                    out.append(f"{a.asname} = {a.name}\n")
        return "".join(out)

    body = tree.body
    for i, node in enumerate(body):
        if i == 0 and isinstance(node, ast.Expr) and isinstance(getattr(node, "value", None), ast.Constant) \
                and isinstance(node.value.value, str):
            cut.append((node.lineno, node.end_lineno, ""))  # module docstring
        elif isinstance(node, ast.ImportFrom) and node.module == "__future__":
            cut.append((node.lineno, node.end_lineno, ""))  # only legal at the top of model.py, which has it
        elif is_paiec(node):
            cut.append((node.lineno, node.end_lineno, aliases([node])))
        elif isinstance(node, ast.Try) and node.body and all(is_paiec(n) for n in node.body):
            cut.append((node.lineno, node.end_lineno, aliases(node.body)))  # try: from paiec... except ImportError
        elif (isinstance(node, ast.If) and isinstance(node.test, ast.Compare)
              and isinstance(node.test.left, ast.Name) and node.test.left.id == "__name__"):
            cut.append((node.lineno, node.end_lineno, ""))  # `if __name__ == "__main__":` demo code
    for first, last, repl in sorted(cut, reverse=True):
        lines[first - 1:last] = [repl] if repl else []
    code = "".join(lines).strip("\n") + "\n"
    stripped = ast.parse(code)
    for node in ast.walk(stripped):
        if isinstance(node, (ast.Import, ast.ImportFrom)) and (_paiec_target(module, node)
                                                               or getattr(node, "level", 0)):
            raise SystemExit(f"{module}: a paiec or relative import remains at line {node.lineno} (nested imports "
                             f"cannot be vendored; move it to the module top level)")
    imports, defs = _bindings(stripped)
    bad = sorted({n for n in imports if n in available_defs}
                 | {n for n, src_ in imports.items() if n in available and available[n] != src_})
    if bad:
        raise SystemExit(f"{module} imports names that the vendored code defines differently: {', '.join(bad)}")
    clash = defs & (available_defs | set(available))
    if clash:  # e.g. a private helper with the same name as one in hier.py/subjects.py: rename the plug-in's copy
        code = _rename(module, code, clash, "__" + module.rsplit(".", 1)[1])
        imports, defs = _bindings(ast.parse(code))
    extra = {m for m, _ in imports.values() if m and m.split(".")[0] not in sys.stdlib_module_names
             and m.split(".")[0] != "numpy"}
    if extra:
        print(f"warning: {module} imports {sorted(extra)} (not stdlib/numpy); check the runtime has them",
              file=sys.stderr)
    return code, imports, defs


def plugin_code(cls_path: str, vendored: str) -> tuple[str, str, list[str]]:
    """(code to append after hier.py, class name, vendored module files) for --plugin paiec.ext.<module>:<Class>."""
    module, _, cls = cls_path.partition(":")
    if not module.startswith("paiec.ext.") or not cls.isidentifier():
        raise SystemExit(f"--plugin must look like paiec.ext.<module>:<Class>, got {cls_path!r}")
    available, available_defs = _bindings(ast.parse(vendored))
    chunks, files = [], []
    for mod in _plugin_order(module, []):
        code, imports, defs = _strip_plugin(mod, available, available_defs)
        rel = _module_path(mod).relative_to(REPO).as_posix()
        chunks.append(f"\n\n# ---- vendored plug-in module {rel} (tools/make_submission.py --plugin) ----\n{code}")
        files.append(rel)
        available.update(imports)
        available_defs |= defs
        if mod == module and cls not in defs:
            raise SystemExit(f"{module} defines no top-level {cls}")
    return "".join(chunks), cls, files


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("name")
    ap.add_argument("--params", required=True, help="JSON params for HierModel (or the plug-in class)")
    ap.add_argument("--prior", choices=["subjects", "subjects_np", "names"], default="subjects")
    ap.add_argument("--plugin", default=None, help="paiec.ext.<module>:<Class> to vendor and ship instead of HierModel "
                                                   "(default: the 'class' key of --params, if any)")
    ap.add_argument("--outdir", type=Path, default=None, help="write here instead of submission_src/<name>")
    args = ap.parse_args()
    params = json.loads(args.params)
    cls_path = args.plugin or params.get("class")
    if args.plugin and params.get("class") not in (None, args.plugin):
        raise SystemExit(f"--plugin {args.plugin} disagrees with params class {params['class']}")
    out = args.outdir.resolve() if args.outdir else REPO / "submission_src" / args.name
    if (out / "model.py").exists():
        print(f"note: overwriting {out}", file=sys.stderr)
    core = _code(REPO / "paiec" / "subjects.py") + _code(REPO / "paiec" / "hier.py")
    if cls_path:  # plug-in build; the default branch below is the unchanged original
        head = THREADS + "\nimport json\nfrom pathlib import Path\n" + core
        extra, cls, files = plugin_code(cls_path, head)
        code = ("from __future__ import annotations\n" + HEADER_PLUGIN.format(name=args.name, files=", ".join(files),
                                                                              cls=cls)
                + head + extra + FOOTER_PLUGIN.format(cls=cls))
        compile(code, str(out / "model.py"), "exec")
        params_text = json.dumps({"class": cls_path, **{k: v for k, v in params.items() if k != "class"}}, indent=1)
    else:
        code = ("from __future__ import annotations\n" + HEADER.format(name=args.name) + THREADS
                + "\nimport json\nfrom pathlib import Path\n" + core + FOOTER)
        params_text = json.dumps(json.loads(args.params), indent=1)
    out.mkdir(parents=True, exist_ok=True)
    for stale in ("abilities.json",):
        (out / stale).unlink(missing_ok=True)
    (out / "model.py").write_text(code)
    (out / "params.json").write_text(params_text)
    df = load_responses(BINARY_BENCHMARKS)
    if args.prior == "subjects_np":  # provider-free attribute ridge (paiec/ext/np_prior.py); predict code unchanged
        from paiec.ext.np_prior import fit_subject_prior_np
        prior = fit_subject_prior_np(df)
    else:
        prior = fit_subject_prior(df) if args.prior == "subjects" else {k: list(v) for k, v in fit_abilities(df).items()}
    (out / "subject_prior.json").write_text(json.dumps(prior, indent=0, sort_keys=True))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
