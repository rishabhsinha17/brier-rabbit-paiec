"""Assemble submission_src/<name>/ for the v1 hierarchical model: vendored model code + params + abilities."""
from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
from paiec.data import BINARY_BENCHMARKS, load_responses  # noqa: E402
from paiec.hier import fit_abilities  # noqa: E402

HEADER = '''"""Brier Rabbit {name}: hierarchical logistic model, Laplace posterior refit from `labeled`, posterior-predictive output.

Generated by tools/make_v1_submission.py from paiec/hier.py. Parameters in params.json, abilities in abilities.json
(fitted on the public measurement-db training pool, revision bc8204d8).
"""
'''

THREADS = '''
import os as _os

# Up to 16 prediction workers share the machine: keep BLAS single-threaded (must run before numpy is imported).
for _var in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS", "VECLIB_MAXIMUM_THREADS"):
    _os.environ.setdefault(_var, "1")
'''

FOOTER = '''

_HERE = Path(__file__).resolve().parent
_PARAMS = json.loads((_HERE / "params.json").read_text())
_ABILITIES = {k: tuple(v) for k, v in json.loads((_HERE / "abilities.json").read_text()).items()}
_MODEL = HierModel(_ABILITIES, _PARAMS)


def predict(input, labeled=None) -> float:
    return _MODEL.predict(input, labeled)
'''


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("name")
    ap.add_argument("--params", required=True, help="JSON params for HierModel")
    args = ap.parse_args()
    out = REPO / "submission_src" / args.name
    out.mkdir(parents=True, exist_ok=True)
    src = (REPO / "paiec" / "hier.py").read_text()
    body = src.split('"""', 2)[2]  # drop the module docstring, keep code
    body = body.replace("from __future__ import annotations\n", "")
    code = "from __future__ import annotations\n" + HEADER.format(name=args.name) + THREADS + "\nfrom pathlib import Path\n" + body + FOOTER
    (out / "model.py").write_text(code)
    params = json.loads(args.params)
    (out / "params.json").write_text(json.dumps(params, indent=1))
    df = load_responses(BINARY_BENCHMARKS)
    abilities = fit_abilities(df)
    (out / "abilities.json").write_text(json.dumps({k: list(v) for k, v in sorted(abilities.items())}, indent=0))
    print(f"wrote {out} ({len(abilities)} abilities)")


if __name__ == "__main__":
    main()
